# --- VERA_SPRITE_ATTR

.equ VERA_SPRITE_ATTR_BASE_ADDR, 0x12001000

# MODEADDR - Sprite RAM Mode and VRAM Address Attribute (16-bit).
.equ VERA_SPRITE_ATTR_MODEADDR_ADDR, 0x0

# MODEADDR.ADDR - VRAM Address bits 16:5.
.equ VERA_SPRITE_ATTR_MODEADDR_ADDR_WIDTH, 12
.equ VERA_SPRITE_ATTR_MODEADDR_ADDR_LSB, 0
.equ VERA_SPRITE_ATTR_MODEADDR_ADDR_MASK, 0xfff
# MODEADDR.MODE - 0=4BPP mode, 1=8BPP mode.
.equ VERA_SPRITE_ATTR_MODEADDR_MODE_WIDTH, 1
.equ VERA_SPRITE_ATTR_MODEADDR_MODE_LSB, 15
.equ VERA_SPRITE_ATTR_MODEADDR_MODE_MASK, 0x8000
# X - Sprite RAM X Attribute (16-bit).
.equ VERA_SPRITE_ATTR_X_ADDR, 0x2

# X.val - Sprite X position.
.equ VERA_SPRITE_ATTR_X_VAL_WIDTH, 10
.equ VERA_SPRITE_ATTR_X_VAL_LSB, 0
.equ VERA_SPRITE_ATTR_X_VAL_MASK, 0x3ff
# Y - Sprite RAM Y Attribute (16-bit).
.equ VERA_SPRITE_ATTR_Y_ADDR, 0x4

# Y.val - Sprite Y position.
.equ VERA_SPRITE_ATTR_Y_VAL_WIDTH, 10
.equ VERA_SPRITE_ATTR_Y_VAL_LSB, 0
.equ VERA_SPRITE_ATTR_Y_VAL_MASK, 0x3ff
# FLAGS - Sprite RAM Flags Attribute (16-bit).
.equ VERA_SPRITE_ATTR_FLAGS_ADDR, 0x6

# FLAGS.HFLIP - Horizontal Flip
.equ VERA_SPRITE_ATTR_FLAGS_HFLIP_WIDTH, 1
.equ VERA_SPRITE_ATTR_FLAGS_HFLIP_LSB, 0
.equ VERA_SPRITE_ATTR_FLAGS_HFLIP_MASK, 0x1
# FLAGS.VFLIP - Vertical Flip
.equ VERA_SPRITE_ATTR_FLAGS_VFLIP_WIDTH, 1
.equ VERA_SPRITE_ATTR_FLAGS_VFLIP_LSB, 1
.equ VERA_SPRITE_ATTR_FLAGS_VFLIP_MASK, 0x2
# FLAGS.ZDEPTH - Z Depth
.equ VERA_SPRITE_ATTR_FLAGS_ZDEPTH_WIDTH, 2
.equ VERA_SPRITE_ATTR_FLAGS_ZDEPTH_LSB, 2
.equ VERA_SPRITE_ATTR_FLAGS_ZDEPTH_MASK, 0xc
# FLAGS.COLMASK - Collision Mask
.equ VERA_SPRITE_ATTR_FLAGS_COLMASK_WIDTH, 4
.equ VERA_SPRITE_ATTR_FLAGS_COLMASK_LSB, 4
.equ VERA_SPRITE_ATTR_FLAGS_COLMASK_MASK, 0xf0
# FLAGS.PALOFFSET - Sprite Palette Offset.
.equ VERA_SPRITE_ATTR_FLAGS_PALOFFSET_WIDTH, 4
.equ VERA_SPRITE_ATTR_FLAGS_PALOFFSET_LSB, 8
.equ VERA_SPRITE_ATTR_FLAGS_PALOFFSET_MASK, 0xf00
# FLAGS.WIDTH - Sprite Width
.equ VERA_SPRITE_ATTR_FLAGS_WIDTH_WIDTH, 2
.equ VERA_SPRITE_ATTR_FLAGS_WIDTH_LSB, 12
.equ VERA_SPRITE_ATTR_FLAGS_WIDTH_MASK, 0x3000
# FLAGS.HEIGHT - Sprite Height
.equ VERA_SPRITE_ATTR_FLAGS_HEIGHT_WIDTH, 2
.equ VERA_SPRITE_ATTR_FLAGS_HEIGHT_LSB, 14
.equ VERA_SPRITE_ATTR_FLAGS_HEIGHT_MASK, 0xc000
