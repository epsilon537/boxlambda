\ BoxLambda Forth
\ USB HID dispatcher

begin-module keyboard

  \ Keyboard detect period in OS ticks.
  \ If no USB HID keyboard reports are received in this period,
  \ the keyboard is considered not present, keyb-present is set to false,
  \ and the keyboard detect board led is turned off.
  100 constant KEYB-DETECT-PERIOD

  \ This variable is true if a USB keyboard is connected.
  false variable keyb-present

  \ The initial repeat delay
  50 variable keyb-repeat-start-ticks
  \ The repeat period in OS ticks.
  4 variable keyb-repeat-period-ticks

  \ keymods bitmask values. Bit definitions of the .modifiers fields
  \ in the structs below.
  $1 constant KEYMOD-LCTRL
  $2 constant KEYMOD-LSHIFT
  $4 constant KEYMOD-LALT
  $8 constant KEYMOD-LWIN
  $10 constant KEYMOD-RCTRL
  $20 constant KEYMOD-RSHIFT
  $40 constant KEYMOD-RALT
  $80 constant KEYMOD-RWIN

  \ Bit definitions of the .flags field in the structs below.
  $1 constant KEY-FLAG-REPEAT
  $2 constant KEY-FLAG-NUM-LOCK
  $4 constant KEY-FLAG-CAPS-LOCK
  $8 constant KEY-FLAG-MAPPED-EVENT

  \ The event struct definition for keyb-get/poll-raw-event (no .key field).
  begin-structure key-event-struct-raw
    cfield: .scancode
    cfield: .modifiers
    cfield: .upndown
    cfield: .flags
  end-structure

  \ The event struct definition for keyb-get/poll-event. Same fields, in the
  \ same order as key-event-struct-raw plus and additional .key field containing
  \ the result of scancode->ascii/key keyboard mapping.
  begin-structure key-event-struct
    cfield: .scancode
    cfield: .modifiers
    cfield: .upndown \ True: key up event, False: key down event.
    cfield: .flags
    cfield: .key
  end-structure

  \ Exceptions
  : x-keymap-not-set ." Keymap not set." cr ;
  : x-keymap-no-end  ." Keymap end sentinel not found." cr ;
  : x-no-repeat-key-overflow ." Too many no-repeat keys." cr ;

  \ Print the keyboard event details.
  (  event|raw-event -- )
  : keyb-event.
    >r ( R: event|raw-event )
    r@ .modifiers c@ r@ .scancode c@
    s" Key event: scancode: $%x modifiers: $%x " printf
    r@ .upndown c@ if ." up " else ." down " then
    r@ .flags c@ ( flags R: event|raw-event )
    dup KEY-FLAG-REPEAT and if ." repeat" then ( flags R: event|raw-event )
    dup KEY-FLAG-NUM-LOCK and if ." num-lock" then ( flags R: event|raw-event )
    dup KEY-FLAG-CAPS-LOCK and if ." caps-lock" then ( flags R: event|raw-event )
    dup KEY-FLAG-MAPPED-EVENT and if ( flags R: event|raw-event )
      ." ascii/key code: " dup .key c@ hex. ( flags R: event|raw-event )
    then
    cr
    drop rdrop
  ;

  \ Enable/disable software test mode. In software test mode, any USB reports
  \ generated by an attached USB HID device are blocked so they can't interfere
  \ with software testing.
  ( f -- )
  : keyb-sw-test-mode USB_HID_0_STATUS_BLOCK_REPORTS! ;

  \ Returns software test mode.
  ( -- f )
  : keyb-sw-test-mode? USB_HID_0_STATUS_BLOCK_REPORTS@ 0<> ;

  begin-module keyb-internals

    hook-os-timer @ variable prev-hook-timer
    0 variable detect-ticks
    0 variable report-count

    0 variable repeat-ticks
    -1 variable repeat-ticks-cmp

    \ Periodically detect keyboard presence (called from os-tick hook). 
    \ Update keyb-present variable and led-keyboard-detect.
    ( -- )
    : keyb-detect
      detect-ticks @ 1+ ( ticks )
      dup KEYB-DETECT-PERIOD >= if ( ticks )
        drop 0 ( ticks)
        report-count @ 0> ( ticks f )
        dup keyb-present ! ( ticks f )
        dup led-keyboard-detect! 0= ( ticks f )
        keyb-sw-test-mode? not and ( ticks f )
        \ Reset the core if keyboard is no longer present to allow re-detect/re-enumeration.
        if RESET_CONTROL_CTRL_USB_RESET RESET_CONTROL_CTRL! then ( ticks )
        0 report-count ! ( ticks )
      then
      detect-ticks ! ( )
    ;

    0 variable prev-keypress \ The previous keys-pressed register value.
    0 variable new-keypress  \ The current keys-pressed register value.
    0 variable prev-keymods \ The previous USB_HID_0_KEY_MODS register value. Left/right folded.
    0 variable new-keymods \ The current USB_HID_0_KEY_MODS register value. Left/right folded.

    \ The keyboard queue with space for 32 events.
    32 queue-create keyb-q

    \ Read keymods register.
    ( -- keymods )
    : read-keymods USB_HID_0_KEY_MODS_ADDR @ ;

    \ Read keys-pressed register.
    ( -- keypress )
    : read-keypress
      USB_HID_0_KEYS_ADDR @ ( keys-pressed )
    ;

    ( -- )
    : update-keymods
      new-keymods @ prev-keymods !
      read-keymods new-keymods !
    ;

    ( -- )
    : update-keypress
      new-keypress @ prev-keypress !
      read-keypress new-keypress !
    ;

  end-module

  \ The raw key-event object to be referred to from the key-event-raw-hook.
  create key-event-raw key-event-struct-raw allot

  \ The default interrupt-level key event hook: add the event to the
  \ keyboard queue.
  ( -- )
  : keyb-q-hook
    \ Pick up all 4 bytes at once.
    key-event-raw .scancode @ keyb-internals :: keyb-q queue-push
  ;

  \ Interrupt-level key event hook. Can be used for 'on-key' type
  \ custom event handling.
  ' keyb-q-hook variable key-event-raw-hook

  keyb-internals continue-module

    \ The scancode of the caps-lock key ( 0 for none )
    SCANCODE-CAPSLOCK variable caps-lock-key

    \ The scancode of the num-lock key ( 0 for none )
    SCANCODE-NUMLOCK variable num-lock-key

    \ Follows the .flags bit definitions for num-lock and caps-lock
    0 variable locked-flags

    : keyb-led! ( mask "name" -- )
      create
        \ compile-time: store the parameter in the dictionary body
        ,
      does> ( f pfa )
        @ ( f mask )
        swap if ( mask )
          USB_HID_0_LEDS_ADDR @ or USB_HID_0_LEDS_ADDR ! ( )
        else
          not USB_HID_0_LEDS_ADDR @ and USB_HID_0_LEDS_ADDR ! ( )
        then
    ;

    : keyb-led@ ( mask "name" -- )
      create
        \ compile-time: store the parameter in the dictionary body
        ,
      does> ( pfa )
        @ ( mask )
        USB_HID_0_LEDS_ADDR @ and 0<>
    ;

    \ Keyboard LED setters
    1 keyb-led! led-num-lock!
    2 keyb-led! led-caps-lock!
    4 keyb-led! led-scroll-lock!
    8 keyb-led! led-compose!

    \ Keyboard LED getters
    1 keyb-led@ led-num-lock@
    2 keyb-led@ led-caps-lock@
    4 keyb-led@ led-scroll-lock@
    8 keyb-led@ led-compose@

    \ Populate the key-event-raw object and invoke the key-event-raw-hook.
    ( scancode upndown flags -- )
    : report-key-event
      -rot ( flags scancode upndown )
      swap key-event-raw .scancode c! ( flags upndown )
      dup if prev-keymods else new-keymods then @ ( flags upndown keymods )
      key-event-raw .modifiers c! ( flags upndown )
      key-event-raw .upndown c! ( flags )
      key-event-raw .flags c! ( )
      key-event-raw-hook @ execute ( )
    ;

    \ Returns true if byte is found in at least one of the byte positions in (32-bit) word.
    ( byte word -- f )
    : find-byte-in-word
      4 0 do ( byte word )
        2dup $ff and = if ( byte word )
          2drop
          unloop true exit
        then
        8 rshift ( byte word' )
      loop
      2drop ( )
      false
    ;

    \ Process caps-lock and num-lock key events at interrupt level (i.e. pre-queue).
    \ Returns true if given key is a num-lock or caps-lock key.
    ( key -- f )
    : handle-lock-key
      case
        num-lock-key @ of
          locked-flags @ KEY-FLAG-NUM-LOCK xor dup locked-flags ! ( flags )
          KEY-FLAG-NUM-LOCK and led-num-lock! ( )
          true
        endof
        caps-lock-key @ of 
          locked-flags @ KEY-FLAG-CAPS-LOCK xor dup locked-flags !
          KEY-FLAG-CAPS-LOCK and led-caps-lock! ( )
          true
        endof
        false swap
      endcase
    ;

    \ process an individual (out of up to four) keydown.
    ( key -- )
    : process-keydn
      \ Only process new keypresses
      dup prev-keypress @ find-byte-in-word if drop exit then ( key )
      \ caps-lock/num-lock key events are handed here. They are not reported.
      dup handle-lock-key if drop exit then ( key )
      \ if queue almost full, erase the keypress. Don't report.
      keyb-q queue-#free 8 < if ( key )
        0 new-keypress i + c! ( )
        drop exit
      then
      false locked-flags @ ( key upndown flags ) \ Parameters for the report-key-event.
      report-key-event ( )
    ;

    ( -- )
    : process-keydns \ Are any of the new keys not yet present in the old key-presses?
      4 0 do \ Iterate over the up-to-four keypresses
        new-keypress i + c@ ( key|0 )
        ?dup if ( key ) \ Only consider actual keypresses. Dismiss the zeros.
          process-keydn ( )
        then ( )
      loop
    ;

    \ process an individual (out of up to four) keyup.
    ( old-key -- )
    : process-keyup
      \ Only process key ups, i.e. keys that are no longer present in the new keypress list.
      dup new-keypress @ find-byte-in-word if drop exit then ( key )
      true locked-flags @ ( key upndown flags ) \ Parameters for the report-key-event.
      report-key-event ( )
    ;

    ( -- )
    : process-keyups \ Are any of the old keys no longer present in the new key-presses?
      4 0 do \ Iterate over the up-to-four keypresses
        prev-keypress i + c@ ( key|0 )
        ?dup if ( key ) \ Only consider actual keypresses. Dismiss the zeros.
          process-keyup ( )
        then ( )
      loop
    ;

    ( v -- )
    : repeat-timer-start
      repeat-ticks-cmp ! ( ) \ Set comparator
      0 repeat-ticks ! \ Restart the timer
    ;

    ( -- )
    : repeat-timer-stop -1 repeat-ticks-cmp ! ;

    \ Invoked by IRQ hander when a key report event has been received.
    ( -- )
    : process-keyreport
      update-keymods
      update-keypress
      new-keypress @ prev-keypress @ <> if \ any key-press changes?
        process-keyups
        process-keydns
        new-keypress @ if \ any keys pressed? -> (re)start the repeat timer.
          keyb-repeat-start-ticks @ repeat-timer-start
        else \ no keys pressed currently -> cancel repeat timer
          repeat-timer-stop
        then
      then
    ;

    \ The USB HID 0 interrupt handler.
    : usb-hid-0-irq-handle
      \ Only consider USB reports (dismiss LED reports)
      USB_HID_0_ISR_USB_REPORT@ if
        \ Acknowledge the USB report interrupt in the USB core.
        1 USB_HID_0_ISR_USB_REPORT!
        USB_HID_0_STATUS_USB_TYP@ USB_HID_0_STATUS_USB_TYP_KEYB = if
          1 report-count +!
          process-keyreport
        then
      then
    ;

    ' usb-hid-0-irq-handle irq-usb_hid_0 !

    \ Keeps track of which keys (max. 4) should not repeat when leaned on.
    0 variable no-repeat-keys

  end-module

  ( scancode -- )
  \ Remove scancode from no-repeat key-list. 
  \ Note: does not complain if given scancode is not found.
  : keyb-no-repeat-key-
    4 0 do ( scancode )
      dup keyb-internals :: no-repeat-keys i + c@ = if ( scancode )
        0 keyb-internals :: no-repeat-keys i + c! ( scancode )
      then ( scancode )
    loop ( scancode )
    drop ( )
  ;

  ( scancode -- )
  \ Add scancode that won't repeat when leaned on.
  \ Throws x-no-repeat-key-overflow if more than 4 no-repeat keys are added.
  : keyb-no-repeat-key+
    \ Attempt to remove the key first, so there are no duplicates.
    dup keyb-no-repeat-key-
    \ Now add the key.
    4 0 do ( scancode )
      \ Find an empty spot
      keyb-internals :: no-repeat-keys i + c@ 0= if ( scancode )
        keyb-internals :: no-repeat-keys i + c!
        unloop exit
      then
    loop
    ['] x-no-repeat-key-overflow ?raise
  ;

  \ List the configured no-repeat keys
  ( -- k0 k1 k2 k3 )
  : keyb-no-repeat-keys@
    4 0 do
      keyb-internals :: no-repeat-keys @ ( k0..kn-1 acc )
      i 8 * rshift $ff and ( k0 .. kn )
    loop
  ;

  keyb-internals continue-module

    \ Report given keypress (unless it's a no-repeat key or the queue is full).
    ( key -- )
    : report-repeat-keypress
      dup no-repeat-keys @ find-byte-in-word ( key f ) \ only repeat keys
      keyb-q queue-#free 8 < or ( key f ) \ and only if queue not full
      if drop exit then ( key )
      false locked-flags @ KEY-FLAG-REPEAT or ( key upndow flags ) \ report-key-event params
      report-key-event ( )
    ;

    \ The repeat timer has expired. Re-report the currently pressed keys (unless they're
    \ no-repeat keys.
    ( -- )
    : report-repeat-keypresses
      new-keypress @
      begin ( keypresses )
        dup while ( keypresses )
          dup $ff and ( keypresses key )
          report-repeat-keypress
          8 rshift ( keypresses )
      repeat ( keypresses )
      drop ( )
    ;

    \ Increment repeat timer and re-report current keypresses if expired.
    ( -- )
    : keyb-repeat-tick
      repeat-ticks @ 1+ ( ticks )
      dup repeat-ticks ! ( ticks )
      repeat-ticks-cmp @ u>= if ( )
        keyb-repeat-period-ticks @ repeat-timer-start
        report-repeat-keypresses
      then
    ;

    \ Hooks into the hook-os-timer chain.
    ( -- )
    : keyb-os-tick
      keyb-detect
      keyb-repeat-tick
      prev-hook-timer @ execute
    ;

    \ The keyboard event popped off the queue is stored here.
    create keyb-poll-latest-event key-event-struct allot

    \ Points to the keymapping table (e.g. see keymap-azerty-be.fs for example).
    0 variable keymap
    \ The number of keymap entries in the keymapping table.
    0 variable keymap-#keys

    \ Returns true if given key is a keypad key with mapping depending on num-lock.
    ( event -- f )
    : keypad-num?
      .scancode c@ ( scancode )
      dup SCANCODE-KEYPAD-1 >= ( scancode f )
      swap SCANCODE-KEYPAD-DOT <= ( f f )
      and
    ;

    \ Temporarily disable runtime typechecking on structs to not incur the typefield overhead.
    rttc-struct @ constant prev-rttc-struct
    false rttc-struct !

    \ This struct matches the layout of the two tables below.
    begin-structure mod-flg-struct
      cfield: .mod-mask
      cfield: .mod-val
      cfield: .flg-mask
      cfield: .flg-val
      cfield: .col
    end-structure

    \ Non-keymap event to keymap column mapping table
    create mod-flg>col
    \ Modifier Mask   Modifier Value        key flags mask       key flags value   column
                $ff c,             0 c, KEY-FLAG-CAPS-LOCK c, KEY-FLAG-CAPS-LOCK c,     1 c,
                $ff c,             0 c, KEY-FLAG-CAPS-LOCK c,                  0 c,     0 c,
      KEYMOD-LSHIFT c, KEYMOD-LSHIFT c, KEY-FLAG-CAPS-LOCK c, KEY-FLAG-CAPS-LOCK c,     0 c,
      KEYMOD-LSHIFT c, KEYMOD-LSHIFT c, KEY-FLAG-CAPS-LOCK c,                  0 c,     1 c,
      KEYMOD-RSHIFT c, KEYMOD-RSHIFT c, KEY-FLAG-CAPS-LOCK c, KEY-FLAG-CAPS-LOCK c,     0 c,
      KEYMOD-RSHIFT c, KEYMOD-RSHIFT c, KEY-FLAG-CAPS-LOCK c,                  0 c,     1 c,
      KEYMOD-RALT   c,   KEYMOD-RALT c,                  0 c,                  0 c,     2 c,
                  0 c,             0 c,                  0 c,                  0 c,     3 c,

    \ Keymap event to keymap column mapping table
    create keypad-mod-flg>col
    \ Modifier Mask   Modifier Value        key flags mask       key flags value   column
                  0 c,             0 c,  KEY-FLAG-NUM-LOCK c,  KEY-FLAG-NUM-LOCK c,     1 c,
                  0 c,             0 c,  KEY-FLAG-NUM-LOCK c,                  0 c,     0 c,

    \ Does mask applied to v match match?
    ( v mask match -- f )
    : maskmatch? -rot and = ;

    ( row mods flags -- f )
    : row-mod-flg-match?
      rot >r ( mod flags R: row )
      r@ .flg-mask c@ r@ .flg-val c@ maskmatch? ( mod f R: row )
      swap r@ .mod-mask c@ r@ .mod-val c@ maskmatch? ( f f R: row )
      and rdrop ( f )
    ;

    \ Event to keymap column mapping.
    ( raw-event -- col )
    : event>keymap-col
      >r ( R: raw-event )
      \ Select mapping table to use.
      r@ keypad-num? if keypad-mod-flg>col else mod-flg>col then
      begin ( row R: raw-event )
        dup r@ .modifiers c@ r@ .flags c@ row-mod-flg-match? not while
          mod-flg-struct +
      repeat ( row R: raw-event )
      .col c@ rdrop ( col )
    ;

    \ Restore runtime typechecking on structs
    prev-rttc-struct rttc-struct !

  end-module

  \ Start the keyboard driver
  ( -- )
  : keyb-start
    \ Reset the core.
    RESET_CONTROL_CTRL_USB_RESET RESET_CONTROL_CTRL!
    \ Clear the USB report interrupt in the USB core.
    1 USB_HID_0_ISR_USB_REPORT!
    1 USB_HID_0_IEN_USB_REPORT!
    mie irq-id-usb-hid-0 1<< or mie!
    keyb-internals ::['] keyb-os-tick hook-os-timer !
  ;

  \ Stop the keyboard driver
  ( -- )
  : keyb-stop
    0 USB_HID_0_IEN_USB_REPORT!
    mie irq-id-usb-hid-0 1<< bic mie!
    keyb-internals ::['] prev-hook-timer hook-os-timer !
  ;

  \ Reset the keyboard queue.
  ( -- )
  : keyb-reset
    keyb-internals :: keyb-q queue-reset
  ;

  \ Returns true if the keyboard queue overflowed.
  ( -- f )
  : keyb-overflow?
    keyb-internals :: keyb-q queue-#free 8 <
  ;

  \ Retuns number of events currently in the keyboard queue.
  ( -- n )
  : keyb-#events-pending
    keyb-internals :: keyb-q queue-depth
  ;

  \ Non-blocking polling for raw (non-mapped) keyboard events.
  ( -- event|0 )
  : keyb-poll-raw-event
    keyb-internals :: keyb-q queue-depth 0> if ( )
      keyb-internals :: keyb-q queue-pop ( event-val )
      \ store all 4 bytes at once.
      keyb-internals :: keyb-poll-latest-event .scancode ! ( )
      \ set .key to 0 for the time being
      0 keyb-internals :: keyb-poll-latest-event .key c! ( )
      keyb-internals :: keyb-poll-latest-event ( event )
    else
      0
    then ( event|0 )
  ;

  \ Blocking wait for raw (non-mapped) keyboard event.
  ( -- raw-event )
  : keyb-get-raw-event
    0
    begin
      drop keyb-poll-raw-event ( event|0)
      dup
    until ( event )
  ;

  \ Set the keymap table
  \ May throw x-keymap-no-end.
  ( keymap -- )
  : keyb-keymap!
    #256 0 do ( keymap )
      dup i 2 lshift + @ ( keymap keymap-row )
      -1 = if ( keymap ) \ keymap tables ends with -1
        i keyb-internals :: keymap-#keys ! ( keymap )
        keyb-internals :: keymap ! ( )
        unloop exit ( )
      then ( keymap )
    loop
    ['] x-keymap-no-end ?raise
  ;

  \ Set the key to be used to toggle num-lock.
  ( scancode -- )
  : keyb-num-lock-key! keyb-internals :: num-lock-key ! ;

  \ Get the key used to toggle num-lock.
  ( --  scancode )
  : keyb-num-lock-key@ keyb-internals :: num-lock-key @ ;

  \ Set the key to be used to toggle caps-lock.
  ( scancode -- )
  : keyb-caps-lock-key! keyb-internals :: caps-lock-key ! ( ) ;

  \ Get the key used to toggle caps-lock.
  ( --  scancode )
  : keyb-caps-lock-key@ keyb-internals :: caps-lock-key @ ;

  \ Non-blocking polling for mapped key events.
  \ May throw keymap-not-set
  : keyb-poll-event
    keyb-poll-raw-event dup 0= if exit then ( raw-event )
    dup .scancode c@ ( raw-event scancode )
    dup keyb-internals :: keymap-#keys >= if drop exit then ( raw-event scancode )
    over keyb-internals :: event>keymap-col ( raw-event scancode col )
    swap 2 lshift + ( raw-event offset )
    keyb-internals :: keymap @ dup averts x-keymap-not-set + c@ ( raw-event mapped-key )
    over .key c! ( event )
    dup .flags dup c@ KEY-FLAG-MAPPED-EVENT or swap c! ( event )
  ;

  \ Blocking wait for mapped keyboard event.
  \ May throw keymap-not-set
  ( -- event )
  : keyb-get-event
    0
    begin
      drop keyb-poll-event ( event|0)
      dup
    until ( event )
  ;

  \ Non-blocking polling for keydown events
  \ May throw keymap-not-set
  ( -- event|0 )
  : keyb-poll-keydown-event
    keyb-poll-event dup if ( event )
      dup .upndown c@ if drop 0 then ( event|0 )
    then ( event|0 )
  ;

  \ Blocking wait for keydown events
  \ May throw keymap-not-set
  ( -- event )
  : keyb-get-keydown-event
    0
    begin
      drop keyb-poll-keydown-event ( event|0 )
      dup
    until ( event )
  ;

  keyb-internals continue-module

    ( -- )
    : test
      begin
        keyb-get-keydown-event ( event )
        dup .scancode c@ SCANCODE-ESCAPE = if ( event )
          drop exit ( )
        then ( event )
        .key c@ emit ( )
      again
    ;
  end-module

end-module

